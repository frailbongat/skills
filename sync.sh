#!/usr/bin/env bash
# Record the third-party skills installed on this machine:
#
#   1. copies ~/.agents/.skill-lock.json into the repo
#   2. regenerates SKILLS.md from it
#
# Run it after installing, updating, or removing a skill, then commit the diff.
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LIVE="$HOME/.agents/.skill-lock.json"
LOCK_FILE="$REPO_DIR/reference-skill-lock.json"
LIST_FILE="$REPO_DIR/SKILLS.md"

# shellcheck source=lockfile.sh
source "$REPO_DIR/lockfile.sh"

if [[ ! -f "$LIVE" ]]; then
  echo "error: no lock file at $LIVE. Nothing to sync." >&2
  exit 1
fi

cp "$LIVE" "$LOCK_FILE"
echo "copied $LIVE -> $LOCK_FILE"

{
  echo "# Third-party skills"
  echo
  echo "Skills other people wrote, installed on my machine by the [Skills CLI](https://skills.sh)."
  echo "\`bootstrap.sh\` installs every row in this table. Not vendored here: each one"
  echo "belongs to its own repo, and a copy would go stale the day upstream edits it."
  echo
  echo "Generated by \`sync.sh\` from \`reference-skill-lock.json\`. Do not edit by hand."
  echo
  echo "| Skill | From | Install |"
  echo "| --- | --- | --- |"

  while IFS=$'\t' read -r name source source_type source_url; do
    [[ -z "$name" ]] && continue
    args="$(install_args "$name" "$source" "$source_type" "$source_url")"
    repo_url="${source_url%.git}"
    if [[ -n "$repo_url" ]]; then
      from="[$source]($repo_url)"
    else
      from="$source"
    fi
    echo "| \`$name\` | $from | \`npx skills add $args -g -y\` |"
  done < <(lock_rows "$LOCK_FILE")

  echo
  echo "Two more skills are on the machine and not in this table, because the Skills CLI"
  echo "does not manage them:"
  echo
  echo "- the Paseo skills, which the Paseo app installs and updates itself"
  echo "- \`impeccable\`, from \`npx impeccable\`, which writes a different copy per agent with that agent's paths in it"
} > "$LIST_FILE"

echo "wrote  $LIST_FILE"
git -C "$REPO_DIR" --no-pager diff --stat -- "$LOCK_FILE" "$LIST_FILE"
